//! One payload member's well-formedness (ITEM-3 / ITEM-7).
//!
//! The release manifest declares a payload as a list of members; this module
//! owns the agreements a single member must satisfy, independent of the
//! document-level rules in [`super::package`]. Splitting here is a
//! responsibility boundary — *what makes one member well-formed* versus *what
//! makes the whole payload agree* — not a size exercise.
//!
//! Every check is pure: it reads the member and, for uniqueness, the role set
//! built so far. Nothing here opens a file or moves a byte.

use std::collections::BTreeSet;

use super::CustomerError;
use super::package::{
    ALL_FORMATS, ManifestFormat, ManifestKind, ManifestMember, is_installed_mode,
    is_lowercase_sha256, is_role, unsupported,
};

/// Rule 5's per-member agreements, composed from three pure checks:
/// [`check_member_shape`] (what this member is), [`check_member_digest`]
/// (whether its digest agrees with `generated`) and [`check_member_scope`]
/// (whether its format scope says why). No check reads manifest state.
pub(crate) fn check_member_agreements<'a>(
    member: &'a ManifestMember,
    roles: &mut BTreeSet<&'a str>,
) -> Result<(), CustomerError> {
    let formats = check_member_shape(member, roles)?;
    check_member_digest(member)?;
    check_member_scope(member, &formats)
}

/// Resolve only safe roles and kinds the sealed bundle builder can stage.
pub(crate) fn bundle_destination(member: &ManifestMember) -> Result<Option<String>, CustomerError> {
    if !member.formats.contains(&ManifestFormat::Bundle) {
        return Ok(None);
    }
    if !is_role(&member.role) {
        return Err(unsupported(format!(
            "release manifest bundle role {:?} is not a safe relative path",
            member.role
        )));
    }
    let prefix = match member.kind {
        ManifestKind::Generated => "",
        ManifestKind::Bin => "bin/",
        ManifestKind::Script
        | ManifestKind::Library
        | ManifestKind::Config
        | ManifestKind::ConfigExample => "scripts/safety/",
        ManifestKind::Unit | ManifestKind::UnitTemplate | ManifestKind::Dropin => "systemd/",
        ManifestKind::Rule
        | ManifestKind::Tmpfiles
        | ManifestKind::Sysusers
        | ManifestKind::Doc => {
            return Err(unsupported(format!(
                "release manifest bundle member {} has no bundle destination",
                member.role
            )));
        }
    };
    Ok(Some(format!("{prefix}{}", member.role)))
}

/// Role shape and uniqueness, installed mode, a real source, and a non-empty
/// format set with no repeats. Returns that format set so the scope check can
/// ask whether the member is shared without rebuilding it.
fn check_member_shape<'a>(
    member: &'a ManifestMember,
    roles: &mut BTreeSet<&'a str>,
) -> Result<BTreeSet<ManifestFormat>, CustomerError> {
    if !is_role(&member.role) {
        return Err(unsupported(format!(
            "release manifest member role {:?} is outside the declared alphabet",
            member.role
        )));
    }
    if !roles.insert(member.role.as_str()) {
        return Err(unsupported(format!(
            "release manifest declares member role {} twice",
            member.role
        )));
    }
    if !is_installed_mode(&member.mode) {
        return Err(unsupported(format!(
            "release manifest member {} mode {:?} is not an installed octal mode",
            member.role, member.mode
        )));
    }
    if member.source.is_empty() {
        return Err(unsupported(format!(
            "release manifest member {} declares no source",
            member.role
        )));
    }
    if member.formats.is_empty() {
        return Err(unsupported(format!(
            "release manifest member {} ships in no format",
            member.role
        )));
    }
    let mut formats = BTreeSet::new();
    for format in &member.formats {
        if !formats.insert(*format) {
            return Err(unsupported(format!(
                "release manifest member {} declares format {} twice",
                member.role,
                format.as_str()
            )));
        }
    }
    Ok(formats)
}

/// A digest agrees with `generated`: generated bytes do not exist at
/// declaration time and so carry no digest, and every other member must.
fn check_member_digest(member: &ManifestMember) -> Result<(), CustomerError> {
    match &member.sha256 {
        Some(digest) if member.kind.is_generated() => {
            return Err(unsupported(format!(
                "release manifest generated member {} carries digest {digest}; generated bytes do not exist at declaration time",
                member.role
            )));
        }
        None if !member.kind.is_generated() => {
            return Err(unsupported(format!(
                "release manifest member {} carries no digest; only generated members may",
                member.role
            )));
        }
        Some(digest) if !is_lowercase_sha256(digest) => {
            return Err(unsupported(format!(
                "release manifest member {} digest {:?} is not a lowercase sha256",
                member.role, digest
            )));
        }
        _ => {}
    }
    Ok(())
}

/// A member carries a reason exactly when it is format-scoped. A shared member
/// with a reason and a scoped member without one are the same defect: an
/// undeclared packaging difference, which DT-8 exists to prevent.
fn check_member_scope(
    member: &ManifestMember,
    formats: &BTreeSet<ManifestFormat>,
) -> Result<(), CustomerError> {
    let shared = member.formats.len() == ALL_FORMATS.len()
        && ALL_FORMATS.iter().all(|format| formats.contains(format));
    if shared == member.reason.is_some() {
        return Err(unsupported(format!(
            "release manifest member {} must carry a reason exactly when it is format-scoped (formats={}, reason={})",
            member.role,
            member
                .formats
                .iter()
                .map(|format| format.as_str())
                .collect::<Vec<_>>()
                .join(","),
            member.reason.is_some()
        )));
    }
    Ok(())
}
