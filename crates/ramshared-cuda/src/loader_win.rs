//! Windows-specific dynamic library loader (using Win32 APIs).
//!
//! Covered requirements: RF-4, DT-5.

use core::ffi::{c_char, c_int, c_void};
use std::ffi::CStr;
use windows_sys::Win32::Foundation::{
    ERROR_INVALID_NAME, ERROR_NO_UNICODE_TRANSLATION, FreeLibrary, GetLastError, HMODULE,
    SetLastError,
};
use windows_sys::Win32::System::LibraryLoader::{
    GetProcAddress, LOAD_LIBRARY_SEARCH_SYSTEM32, LoadLibraryExW,
};
use windows_sys::Win32::System::SystemInformation::GetSystemDirectoryW;

/// Opens an ASCII DLL basename from the native Windows system directory.
/// Driver dependencies use that directory too; ambient search paths are excluded.
///
/// # Safety
/// The `filename` pointer must point to a valid null-terminated C-string.
pub unsafe fn open(filename: *const c_char) -> *mut c_void {
    // SAFETY: caller guarantees `filename` is a valid null-terminated C-string (see # Safety).
    let cstr = unsafe { CStr::from_ptr(filename) };
    let string_str = match cstr.to_str() {
        Ok(s) => s,
        Err(_) => {
            // SAFETY: sets only this thread's error value.
            unsafe { SetLastError(ERROR_NO_UNICODE_TRANSLATION) };
            return core::ptr::null_mut();
        }
    };
    if string_str.is_empty()
        || string_str.len() > 255
        || string_str.ends_with('.')
        || !string_str
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-' | b'.'))
    {
        // SAFETY: sets only this thread's error value.
        unsafe { SetLastError(ERROR_INVALID_NAME) };
        return core::ptr::null_mut();
    }
    // Bounded by the Windows extended-path UTF-16 limit, independently of
    // environment variables. An absolute path also avoids basename reuse of
    // an unrelated module already loaded from a different directory.
    let mut wide = vec![0u16; 32768];
    // SAFETY: the output buffer owns its declared capacity for this native call.
    let length = unsafe { GetSystemDirectoryW(wide.as_mut_ptr(), wide.len() as u32) } as usize;
    if length == 0 {
        return core::ptr::null_mut();
    }
    if length + string_str.len() + 2 > wide.len() {
        unsafe { SetLastError(ERROR_INVALID_NAME) };
        return core::ptr::null_mut();
    }
    wide.truncate(length);
    wide.push(b'\\' as u16);
    wide.extend(string_str.encode_utf16());
    wide.push(0);
    // SAFETY: absolute system path is terminated and owned through the call;
    // dependencies are restricted to System32 by the documented search flag.
    unsafe {
        LoadLibraryExW(
            wide.as_ptr(),
            core::ptr::null_mut(),
            LOAD_LIBRARY_SEARCH_SYSTEM32,
        )
    }
}

/// Loads the specified symbol from the library.
///
/// # Safety
/// `handle` must be a valid pointer returned by `open`.
/// `symbol` must point to a valid null-terminated C-string.
pub unsafe fn sym(handle: *mut c_void, symbol: *const c_char) -> *mut c_void {
    if handle.is_null() {
        return core::ptr::null_mut();
    }
    // GetProcAddress returns Option<unsafe extern "system" fn() -> isize> in windows-sys 0.61.
    // SAFETY: `handle` is a non-null module handle from `open`; `symbol` is a caller-guaranteed
    // null-terminated C-string (see # Safety). The cast to `*const u8` is the windows-sys LPCSTR.
    let addr = unsafe { GetProcAddress(handle as HMODULE, symbol as *const u8) };
    match addr {
        Some(f) => f as *mut c_void,
        None => core::ptr::null_mut(),
    }
}

/// Closes the dynamic library.
///
/// # Safety
/// `handle` must be a valid pointer returned by `open` that has not been closed yet.
pub unsafe fn close(handle: *mut c_void) -> c_int {
    if handle.is_null() {
        return 0;
    }
    // SAFETY: `handle` is a non-null module handle from `open` that has not yet been closed
    // (see # Safety); FreeLibrary decrements the loader reference count once.
    let ok = unsafe { FreeLibrary(handle as HMODULE) };
    if ok != 0 {
        0 // Returns 0 for success, matching dlclose behavior
    } else {
        -1 // Failure
    }
}

/// Returns the last error message generated by the loader using GetLastError().
pub fn error() -> String {
    // SAFETY: GetLastError is a thread-local query with no pointer argument; it cannot fault.
    let code = unsafe { GetLastError() };
    format!("Windows error code: 0x{code:08X}")
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used)]

    use super::*;
    use windows_sys::Win32::Foundation::SetLastError;

    #[test]
    #[ignore = "read-only: requires installed native NVIDIA CUDA and NVML driver DLLs"]
    fn windows_installed_driver_libraries_resolve_from_system_directory() {
        use windows_sys::Win32::System::LibraryLoader::GetModuleFileNameW;
        let mut directory = [0u16; 32768];
        let length = unsafe { GetSystemDirectoryW(directory.as_mut_ptr(), directory.len() as u32) };
        assert!(length > 0 && (length as usize) < directory.len());
        let directory =
            std::path::PathBuf::from(String::from_utf16(&directory[..length as usize]).unwrap());
        for name in [c"nvcuda.dll", c"nvml.dll"] {
            let handle = unsafe { open(name.as_ptr()) };
            assert!(
                !handle.is_null(),
                "installed driver load refused: {name:?}: {}",
                error()
            );
            let mut loaded = [0u16; 32768];
            let length =
                unsafe { GetModuleFileNameW(handle, loaded.as_mut_ptr(), loaded.len() as u32) };
            assert!(length > 0 && (length as usize) < loaded.len());
            let path =
                std::path::PathBuf::from(String::from_utf16(&loaded[..length as usize]).unwrap());
            assert_eq!(path.parent(), Some(directory.as_path()));
            assert_eq!(unsafe { close(handle) }, 0);
        }
        // Driver initialization and immutable device metadata only. No context
        // creation, primary-context retain or memory allocation API is called.
        let cuda = crate::Cuda::load().unwrap();
        assert!(cuda.device_count().unwrap() > 0);
        assert!(cuda.device(0).unwrap().adapter_identity().is_some());
    }

    #[test]
    fn windows_loader_opens_system_library_and_owns_its_symbols() {
        // SAFETY: static C strings and one owned loader reference. No GPU APIs.
        let handle = unsafe { open(c"kernel32.dll".as_ptr()) };
        assert!(!handle.is_null(), "system DLL unavailable: {}", error());
        assert!(!unsafe { sym(handle, c"GetCurrentProcessId".as_ptr()) }.is_null());
        assert!(unsafe { sym(handle, c"ramshared_missing_system_symbol".as_ptr()) }.is_null());
        assert_eq!(unsafe { close(handle) }, 0);
        assert!(unsafe { sym(core::ptr::null_mut(), c"GetCurrentProcessId".as_ptr()) }.is_null());
        assert_eq!(unsafe { close(core::ptr::null_mut()) }, 0);
    }

    #[test]
    fn windows_loader_refusals_set_a_current_native_error() {
        for (name, expected) in [
            (c"", ERROR_INVALID_NAME),
            (c"kernel32.dll ", ERROR_INVALID_NAME),
            (c"\\\\server\\driver.dll", ERROR_INVALID_NAME),
            (c"x:y.dll", ERROR_INVALID_NAME),
            (c"\xff", ERROR_NO_UNICODE_TRANSLATION),
        ] {
            unsafe { SetLastError(0) };
            assert!(unsafe { open(name.as_ptr()) }.is_null());
            assert_eq!(unsafe { GetLastError() }, expected);
        }
        let long = std::ffi::CString::new("a".repeat(256)).unwrap();
        assert!(unsafe { open(long.as_ptr()) }.is_null());
        assert_eq!(unsafe { GetLastError() }, ERROR_INVALID_NAME);
        assert!(unsafe { open(c"ramshared_nonexistent_system_library.dll".as_ptr()) }.is_null());
        assert_ne!(unsafe { GetLastError() }, 0);
    }

    fn assert_working_directory_child_refusals(dll: &CStr) {
        // SAFETY: the name is a static terminated string; close only owns
        // a handle actually returned by this call, including on RED.
        let handle = unsafe { open(dll.as_ptr()) };
        if !handle.is_null() {
            assert_eq!(unsafe { close(handle) }, 0);
        }
        assert!(handle.is_null(), "loaded a DLL from the working directory");
        // Preloading a same-basename module must not transfer trust to it.
        use windows_sys::Win32::System::LibraryLoader::{
            LOAD_LIBRARY_SEARCH_SYSTEM32, LoadLibraryExW,
        };
        let fixture = std::env::current_dir().unwrap().join(dll.to_str().unwrap());
        let path: Vec<u16> = fixture
            .to_str()
            .unwrap()
            .encode_utf16()
            .chain(Some(0))
            .collect();
        let loaded = unsafe {
            LoadLibraryExW(
                path.as_ptr(),
                core::ptr::null_mut(),
                LOAD_LIBRARY_SEARCH_SYSTEM32,
            )
        };
        assert!(!loaded.is_null());
        let reopened = unsafe { open(dll.as_ptr()) };
        if !reopened.is_null() {
            assert_eq!(unsafe { close(reopened) }, 0);
        }
        assert_ne!(unsafe { FreeLibrary(loaded) }, 0);
        assert!(
            reopened.is_null(),
            "reused a module from an unrelated directory"
        );
    }

    #[test]
    fn windows_loader_refuses_a_dll_from_the_working_directory() {
        const CHILD: &str = "RAMSHARED_LOADER_CWD_TEST_CHILD";
        const DLL: &CStr = c"ramshared_untrusted_loader_fixture.dll";
        if std::env::var_os(CHILD).is_some() {
            assert_working_directory_child_refusals(DLL);
            return;
        }
        use windows_sys::Win32::System::LibraryLoader::{
            GetModuleFileNameW, LOAD_LIBRARY_SEARCH_SYSTEM32, LoadLibraryExW,
        };
        let name: Vec<u16> = "version.dll\0".encode_utf16().collect();
        // SAFETY: trusted OS fixture, explicit system-only lookup and owned
        // output buffer. This does not initialize CUDA or load a GPU driver.
        let module = unsafe {
            LoadLibraryExW(
                name.as_ptr(),
                core::ptr::null_mut(),
                LOAD_LIBRARY_SEARCH_SYSTEM32,
            )
        };
        assert!(!module.is_null());
        let mut path = [0u16; 32768];
        let length = unsafe { GetModuleFileNameW(module, path.as_mut_ptr(), path.len() as u32) };
        assert!(length > 0 && (length as usize) < path.len());
        assert_ne!(unsafe { FreeLibrary(module) }, 0);
        let source = String::from_utf16(&path[..length as usize]).unwrap();
        let directory = std::env::temp_dir().join(format!(
            "ramshared-loader-cwd-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        std::fs::create_dir(&directory).unwrap();
        let fixture = directory.join(DLL.to_str().unwrap());
        std::fs::copy(source, &fixture).unwrap();
        let status = std::process::Command::new(std::env::current_exe().unwrap())
            .args([
                "--exact",
                "loader_win::tests::windows_loader_refuses_a_dll_from_the_working_directory",
                "--nocapture",
            ])
            .env(CHILD, "1")
            .current_dir(&directory)
            .stdin(std::process::Stdio::null())
            .status()
            .unwrap();
        std::fs::remove_file(fixture).unwrap();
        std::fs::remove_dir(directory).unwrap();
        assert!(
            status.success(),
            "isolated working-directory refusal failed"
        );
    }

    #[test]
    fn windows_loader_rejects_explicit_and_relative_library_paths() {
        // An explicit system DLL path must not bypass the driver's basename
        // contract, even when the target itself is a trusted system module.
        let mut directory = [0u16; 32768];
        let length = unsafe { GetSystemDirectoryW(directory.as_mut_ptr(), directory.len() as u32) };
        assert!(length > 0 && (length as usize) < directory.len());
        let absolute = format!(
            "{}\\kernel32.dll",
            String::from_utf16(&directory[..length as usize]).unwrap()
        );
        assert!(std::path::Path::new(&absolute).is_file());
        let absolute = std::ffi::CString::new(absolute).unwrap();
        for name in [
            absolute.as_c_str(),
            c".\\kernel32.dll",
            c"../kernel32.dll",
            c"kernel32.dll.",
            c"",
        ] {
            let handle = unsafe { open(name.as_ptr()) };
            if !handle.is_null() {
                assert_eq!(unsafe { close(handle) }, 0);
            }
            assert!(
                handle.is_null(),
                "unexpected library path accepted: {name:?}"
            );
        }
    }

    #[test]
    fn test_error_formatting() {
        // SAFETY: SetLastError writes the calling thread's last-error code only.
        unsafe { SetLastError(0x00000005) };
        assert_eq!(error(), "Windows error code: 0x00000005");

        // SAFETY: SetLastError writes the calling thread's last-error code only.
        unsafe { SetLastError(0xC0000005) };
        assert_eq!(error(), "Windows error code: 0xC0000005");

        // SAFETY: SetLastError writes the calling thread's last-error code only.
        unsafe { SetLastError(0) };
        assert_eq!(error(), "Windows error code: 0x00000000");
    }
}
